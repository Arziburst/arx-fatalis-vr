<#
.SYNOPSIS
	Create an "Arx Fatalis VR" desktop shortcut that runs the current build of a working copy.

.DESCRIPTION
	The shortcut starts whatever branch is checked out in the working copy, using its latest build
	(run-windows.ps1). When the build is stale - another commit than HEAD, uncommitted changes, no
	build - it rebuilds first (launch-shortcut.ps1, the same rule as test-pr.ps1); a failed build keeps
	the log on screen and the game does not start.

	A small launcher is written to %LOCALAPPDATA%\ArxFatalisVR\launch.ps1; it calls launch-shortcut.ps1.
	The window shows the branch, "building <sha>" or "up to date", and waits for Enter on an error. The icon is copied to
	%LOCALAPPDATA%\ArxFatalisVR as well, so the shortcut keeps working whatever is checked out.

.PARAMETER WorkingCopy
	The working copy to run. Default: the one containing this script.

.PARAMETER Icon
	Icon file. Default: data\vr\ARXVR.ico of the working copy containing this script.

.EXAMPLE
	.\scripts\create-desktop-shortcut.ps1
#>
[CmdletBinding()]
param(
	[string]$WorkingCopy = (Split-Path -Parent $PSScriptRoot),
	[string]$Icon = (Join-Path (Split-Path -Parent $PSScriptRoot) 'data\vr\ARXVR.ico')
)

$ErrorActionPreference = 'Stop'
$WorkingCopy = [IO.Path]::GetFullPath($WorkingCopy)
$appDir = Join-Path $env:LOCALAPPDATA 'ArxFatalisVR'
New-Item -ItemType Directory -Force -Path $appDir | Out-Null

$iconCopy = Join-Path $appDir 'ARXVR.ico'
Copy-Item -Force $Icon $iconCopy

$launcher = Join-Path $appDir 'launch.ps1'
@"
# Generated by scripts\create-desktop-shortcut.ps1 - rebuilds if stale, then runs the working copy.
# The logic lives in scripts\launch-shortcut.ps1 of the working copy, so it needs no regeneration.
& (Join-Path '$WorkingCopy' 'scripts\launch-shortcut.ps1') -WorkingCopy '$WorkingCopy'
"@ | Set-Content -Encoding UTF8 $launcher

$desktop = [Environment]::GetFolderPath('Desktop')
$link = Join-Path $desktop 'Arx Fatalis VR.lnk'
$pwsh = (Get-Command pwsh -ErrorAction SilentlyContinue).Source
if (-not $pwsh) { $pwsh = (Get-Command powershell).Source }

$shell = New-Object -ComObject WScript.Shell
$shortcut = $shell.CreateShortcut($link)
$shortcut.TargetPath = $pwsh
$shortcut.Arguments = "-NoProfile -ExecutionPolicy Bypass -File `"$launcher`""
$shortcut.WorkingDirectory = $WorkingCopy
$shortcut.IconLocation = "$iconCopy,0"
$shortcut.Description = "Arx Fatalis VR - runs the current build of $WorkingCopy"
$shortcut.Save()

Write-Host "Created $link -> $WorkingCopy"
